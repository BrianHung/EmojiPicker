// The shadcn-installed component in a fresh app: render, search, popover, tapback.
import { chromium } from "playwright";
const b = await chromium.launch({ channel: "chrome", headless: true });
const p = await b.newPage({ viewport: { width: 1100, height: 760 }, deviceScaleFactor: 2 });
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
p.on("console", (m) => m.type() === "error" && errors.push(m.text().slice(0, 160)));
const requests = [];
p.on("request", (r) => requests.push(new URL(r.url()).pathname.split("/").pop()));
await p.goto("http://localhost:5310/");
const card = p.locator('[data-slot="emoji-picker"]').first();
await card.locator('[data-slot="emoji"]').first().waitFor();
await card.locator('[data-slot="search-input"]').fill("party");
await p.waitForTimeout(300);
const top = await card.evaluate((c) => [...c.querySelectorAll('[data-results] [data-slot="emoji"]')].slice(0, 5).map((e) => e.textContent).join(" "));
await p.keyboard.press("Enter");
const pickedCard = await p.getByTestId("picked").textContent();
await p.getByRole("button", { name: "Open emoji picker" }).click();
const content = p.locator('[data-slot="popover-content"]');
await content.locator('[data-slot="emoji"]').first().waitFor();
const opened = await content.count();
await p.screenshot({ path: "out/fresh-app.png" });
await content.locator('[data-slot="emoji"]').nth(2).click();
await p.waitForTimeout(200);
const closedOnPick = (await content.count()) === 0;
const pickedPopover = await p.getByTestId("picked").textContent();
await p.getByRole("button", { name: "Open emoji picker" }).click();
await p.keyboard.press("Escape");
await p.waitForTimeout(100);
const closedOnEscape = (await content.count()) === 0;
const focusBack = await p.evaluate(() => document.activeElement?.getAttribute("aria-label"));
const tapback = await p.locator('[role="toolbar"], [data-slot="reactions"]').first().evaluate((t) => t.textContent);
console.log({ searchTop: top, pickedCard, popoverOpened: opened === 1, closedOnPick, pickedPopover, closedOnEscape, focusBack, tapback: tapback?.slice(0, 20) });
console.log("engine default data fetched:", requests.some((r) => /^emojis-/.test(r)), "| our data:", requests.filter((r) => /^en-.*\.json$/.test(r)).length, "| errors:", errors.length ? errors : "none");
await b.close();
