import { chromium } from "playwright";
const b = await chromium.connectOverCDP("http://127.0.0.1:9333");
const page = b.contexts()[0].pages().find((p) => p.url().includes("index.html"));
await page.mouse.click(640, 722);
await page.keyboard.type(":smi", { delay: 50 });
await page.waitForTimeout(500);
console.log(await page.evaluate(() => {
  const menu = document.querySelector(".sand-emoji-menu"); const M = menu.getBoundingClientRect();
  const st = (sel) => { const e = menu.querySelector(sel) ?? (sel === "menu" ? menu : null); if (!e) return sel + " missing"; const r = e.getBoundingClientRect(), s = getComputedStyle(e); return `${sel}: ${Math.round(r.x - M.x)},${Math.round(r.y - M.y)} ${r.width}x${r.height} bg=${s.backgroundColor} color=${s.color} font=${s.fontSize}/${s.lineHeight} ${s.fontWeight} ${s.fontFamily.slice(0, 30)} radius=${s.borderRadius} pad=${s.padding} border=${s.border} shadow=${s.boxShadow.slice(0, 90)}`; };
  const hl = menu.querySelector(".sand-emoji-cell[aria-selected=true], .sand-emoji-cell[data-highlighted], .sand-emoji-cell:first-child");
  const hs = getComputedStyle(hl);
  const glyph = hl.querySelector("*") ?? hl; const gs = getComputedStyle(glyph);
  return [st("menu"), st(".sand-emoji-picker__results"), st(".sand-emoji-picker__section-label"), st(".sand-emoji-picker__grid"), st(".sand-emoji-cell"), `highlight bg=${hs.backgroundColor} attrs=${[...hl.attributes].map((a) => a.name).join(",")}`, `glyph ${glyph.tagName} font=${gs.fontSize}`, `menu classes=${menu.className}`].join("\n");
}));
await page.keyboard.press("Escape");
for (let i = 0; i < 4; i++) await page.keyboard.press("Backspace");
await page.getByRole("button", { name: "Composer actions" }).click();
await page.waitForTimeout(400);
console.log("composer menu:", await page.evaluate(() => [...document.querySelectorAll("[role=menuitem], [role=menu] button")].map((e) => (e.textContent || e.getAttribute("aria-label") || "").trim()).join(" | ")));
await page.screenshot({ path: "out/grok-plus.png" });
await page.keyboard.press("Escape");
console.log("composer after:", JSON.stringify(await page.evaluate(() => document.querySelector("[role=textbox]")?.textContent)));
await b.close();
