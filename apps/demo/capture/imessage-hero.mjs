// The scaled iMessage mockup on the demo page: tapback, emoji keyboard, search, scroll, react.
import { chromium } from "playwright";
const b = await chromium.launch({ channel: "chrome", headless: true });
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
await p.goto("http://localhost:5199/");
const phone = p.locator("[data-imessage]").first();
await phone.locator('[role="toolbar"]').waitFor();
const out = {};
await phone.getByRole("button", { name: "Heart" }).click();
out.heartBadge = await phone.evaluate((s) => !!s.querySelector('[data-text]')?.closest("[role=button]") && [...s.querySelectorAll("[role=button] img, [role=button] span")].length > 0);
out.closedAfterTapback = (await phone.locator('[role="toolbar"]').count()) === 0;
const last = phone.getByRole("button", { name: /Long-press to react/ }).last();
await last.dblclick();
await phone.getByRole("button", { name: "More emoji" }).click();
const kb = phone.locator('[data-slot="emoji-picker"]');
await kb.locator('[data-slot="emoji"]').first().waitFor();
out.columns = await kb.evaluate((k) => new Set([...k.querySelectorAll('[data-slot="emoji"]')].slice(0, 20).map((c) => Math.round(c.getBoundingClientRect().top))).size > 1 ? [...k.querySelectorAll('[data-slot="emoji"]')].filter((c, i, a) => Math.round(c.getBoundingClientRect().top) === Math.round(a[0].getBoundingClientRect().top)).length : 0);
await kb.locator('[data-slot="viewport"]').evaluate((v) => (v.scrollTop = 1500));
await p.waitForTimeout(300);
out.cellsAfterScroll = await kb.evaluate((k) => [...k.querySelectorAll('[data-slot="emoji"]')].filter((c) => { const r = c.getBoundingClientRect(), vr = k.querySelector('[data-slot="viewport"]').getBoundingClientRect(); return r.bottom > vr.top && r.top < vr.bottom; }).length);
await kb.locator('[data-slot="search-input"]').fill("rocket");
await p.waitForTimeout(300);
out.searchTop = await kb.evaluate((k) => k.querySelector('[data-results] [data-slot="emoji"]')?.textContent);
await p.keyboard.press("Enter");
await p.waitForTimeout(200);
out.closedAfterPick = (await phone.locator('[data-slot="emoji-picker"]').count()) === 0;
out.rocketBadge = await phone.evaluate((s) => s.textContent.includes("🚀"));
await phone.screenshot({ path: "out/imessage-hero.png" });
console.log(out, errors.length ? errors : "no errors");
await b.close();
